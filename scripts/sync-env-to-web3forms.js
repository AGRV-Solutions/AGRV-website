#!/usr/bin/env node
/**
 * Reads `.env` and writes `web3forms-config.js` for the contact form.
 * Run from repo root:  node scripts/sync-env-to-web3forms.js
 */
var fs = require('fs');
var path = require('path');

var root = path.join(__dirname, '..');
var envPath = path.join(root, '.env');
var outPath = path.join(root, 'web3forms-config.js');

function loadEnv(filePath) {
  var env = {};
  if (!fs.existsSync(filePath)) {
    return env;
  }
  fs.readFileSync(filePath, 'utf8').split(/\r?\n/).forEach(function (line) {
    line = line.trim();
    if (!line || line.indexOf('#') === 0) return;
    var eq = line.indexOf('=');
    if (eq === -1) return;
    var key = line.slice(0, eq).trim();
    var val = line.slice(eq + 1).trim();
    if ((val.charAt(0) === '"' && val.charAt(val.length - 1) === '"') ||
        (val.charAt(0) === "'" && val.charAt(val.length - 1) === "'")) {
      val = val.slice(1, -1);
    }
    env[key] = val;
  });
  return env;
}

var env = loadEnv(envPath);
var key = env.WEB3FORMS_ACCESS_KEY || '';

var contents = '/* Generated by scripts/sync-env-to-web3forms.js — do not commit */\n';
contents += 'window.AGRV_WEB3FORMS_KEY = ' + JSON.stringify(key) + ';\n';

fs.writeFileSync(outPath, contents, 'utf8');

if (key) {
  console.log('OK: web3forms-config.js written (key length: ' + key.length + ').');
} else {
  console.warn('Warning: WEB3FORMS_ACCESS_KEY is empty in .env — contact form will not send until you set it.');
}
