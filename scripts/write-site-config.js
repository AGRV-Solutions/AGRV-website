#!/usr/bin/env node
/**
 * Writes gitignored `site-config.js` from:
 *   1) `.env` file (local dev), then
 *   2) process.env (overrides — used by GitHub Actions with secrets)
 *
 * Run from repo root:  node scripts/write-site-config.js
 */
var fs = require('fs');
var path = require('path');

var root = path.join(__dirname, '..');
var envPath = path.join(root, '.env');
var outPath = path.join(root, 'site-config.js');

function parseEnvFile(filePath) {
  var env = {};
  if (!fs.existsSync(filePath)) return env;
  fs.readFileSync(filePath, 'utf8').split(/\r?\n/).forEach(function (line) {
    line = line.trim();
    if (!line || line.indexOf('#') === 0) return;
    var eq = line.indexOf('=');
    if (eq === -1) return;
    var key = line.slice(0, eq).trim();
    var val = line.slice(eq + 1).trim();
    if ((val.charAt(0) === '"' && val.charAt(val.length - 1) === '"') ||
        (val.charAt(0) === "'" && val.charAt(val.length - 1) === "'")) {
      val = val.slice(1, -1);
    }
    env[key] = val;
  });
  return env;
}

var fromFile = parseEnvFile(envPath);
var keys = ['WEB3FORMS_ACCESS_KEY', 'GA_MEASUREMENT_ID'];
var merged = {};
keys.forEach(function (k) {
  merged[k] = process.env[k] || fromFile[k] || '';
});

var web3 = merged.WEB3FORMS_ACCESS_KEY;
var ga = merged.GA_MEASUREMENT_ID.trim();

var contents =
  '/* Generated by scripts/write-site-config.js — do not commit */\n' +
  'window.AGRV_WEB3FORMS_KEY = ' +
  JSON.stringify(web3) +
  ';\n' +
  'window.AGRV_GA_MEASUREMENT_ID = ' +
  JSON.stringify(ga) +
  ';\n';

fs.writeFileSync(outPath, contents, 'utf8');

console.log('Wrote site-config.js');
if (!web3) console.warn('  WEB3FORMS_ACCESS_KEY is empty — contact form will not send.');
if (!ga) console.warn('  GA_MEASUREMENT_ID is empty — Google Analytics will not load.');
